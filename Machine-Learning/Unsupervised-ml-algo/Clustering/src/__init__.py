# ============================================================================
# Unsupervised Machine Learning Package - K-Means Clustering
# ============================================================================
# This package contains the K-Means clustering pipeline for grouping patients
# in the Pima Indians Diabetes Dataset without target labels.
# Modules:
#   - config:                Centralized configuration for all pipeline parameters.
#   - logger:                Structured logging setup with console outputs.
#   - data_loader:           Data ingestion, validation, and standardisation.
#   - kmeans_clustering:     K-Means algorithm fit, evaluation metrics (elbow, silhouette),
#                            and plotting logic.
#   - main:                  Orchestrator entry point.
