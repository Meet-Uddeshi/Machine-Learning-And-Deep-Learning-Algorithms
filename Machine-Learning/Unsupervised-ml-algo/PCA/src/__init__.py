# ============================================================================
# Unsupervised Machine Learning Package - Principal Component Analysis (PCA)
# ============================================================================
# This package contains the PCA pipeline for dimensionality reduction and feature
# analysis using the Vehicle Silhouettes Dataset.
# Modules:
#   - config:       Centralized configuration for all pipeline parameters.
#   - logger:       Structured logging setup with console outputs.
#   - data_loader:  Data ingestion, null imputation, and standardisation.
#   - pca_service:  PCA fitting, variance calculations, scree plot, loadings,
#                   and projection visualisations.
#   - main:         Orchestration entry point.
# ============================================================================
