# ============================================================================
# Unsupervised Machine Learning Package - Market Basket Analysis & Apriori
# ============================================================================
# This package contains the Market Basket Analysis (MBA) and Apriori algorithm
# pipeline for association rule mining on Online Retail transaction data.
# Modules:
#   - config:           Centralized configuration for all pipeline parameters.
#   - logger:           Structured logging setup with console outputs.
#   - data_loader:      Data ingestion, transaction cleaning, and basket creation.
#   - apriori_service:  Candidate generation, frequent itemsets, rule mining
#                       (Support, Confidence, Lift, Leverage, Conviction),
#                       visualisations, and reports.
#   - main:             Orchestration entry point.
